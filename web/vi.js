function translateDisplay(value) {
  if (!value || !/[A-Za-z]/.test(value)) return value;
  const trimmed=value.trim();
  if (viTerms[trimmed]) return value.replace(trimmed,viTerms[trimmed]);
  const errorParts=trimmed.match(/^([^:]+): (.+)$/);
  if (errorParts && (viTerms[errorParts[1]] || viTerms[errorParts[2]])) {
    const localized=`${viTerms[errorParts[1]] || errorParts[1]}: ${viTerms[errorParts[2]] || errorParts[2]}`;
    return value.replace(trimmed,localized);
  }
  let result=value;
  for (const [pattern,replacement] of viPatterns) result=result.replace(pattern,replacement);
  return result;
}

function translateTree(root) {
  if (root.nodeType===Node.TEXT_NODE) {
    if (root.parentElement?.closest('code,pre,script,style,.record-id,.vehicle-name,.avatar,.account-username,[data-i18n-raw]')) return;
    const next=translateDisplay(root.nodeValue);
    if (next!==root.nodeValue) root.nodeValue=next;
    return;
  }
  if (root.nodeType!==Node.ELEMENT_NODE || root.matches('script,style,code,pre')) return;
  for (const attr of ['placeholder','title','aria-label']) {
    if (root.hasAttribute(attr)) {
      const previous=root.getAttribute(attr), next=translateDisplay(previous);
      if (next!==previous) root.setAttribute(attr,next);
    }
  }
  for (const child of root.childNodes) translateTree(child);
}

